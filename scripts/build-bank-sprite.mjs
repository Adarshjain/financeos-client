// Builds public/banks/sprite-<hash>.png and src/features/banks/bankSprite.generated.ts.
//
// Logos come from https://github.com/praveenpuglia/indian-banks (assets/logos/<ifsc slug>/symbol.svg).
// Clone it anywhere and pass the checkout path:
//   node scripts/build-bank-sprite.mjs /path/to/indian-banks
// Banks that repo does not carry (Amex) use a local PNG from scripts/bank-logos/<id>.png.
// Adding a bank: add it to src/features/banks/banks.ts and to SOURCES below, then rerun.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const CELL = 96;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Our bank id -> indian-banks slug (the lowercase IFSC prefix), or a local file under scripts/bank-logos. */
const SOURCES = {
  amex: { local: 'amex.png' },
  au: { slug: 'aubl' },
  axis: { slug: 'utib' },
  bank_of_baroda: { slug: 'barb' },
  canara: { slug: 'cnrb' },
  csb: { slug: 'csbk' },
  equitas: { slug: 'esfb' },
  federal: { slug: 'fdrl' },
  hdfc: { slug: 'hdfc' },
  hsbc: { slug: 'hsbc' },
  icici: { slug: 'icic' },
  idfc_first: { slug: 'idfb' },
  indian_bank: { slug: 'idib' },
  indusind: { slug: 'indb' },
  kotak: { slug: 'kkbk' },
  sbi: { slug: 'sbin' },
  sbm: { slug: 'stcb' },
  slice: { slug: 'nesf' },
  unity: { slug: 'unba' },
  yes: { slug: 'yesb' },
};

const repo = process.argv[2];
if (!repo || !existsSync(path.join(repo, 'assets/logos'))) {
  console.error('usage: node scripts/build-bank-sprite.mjs <path to indian-banks checkout>');
  process.exit(1);
}

const ids = Object.keys(SOURCES).sort();

async function cell(id) {
  const src = SOURCES[id];
  let input;
  if (src.local) {
    input = sharp(path.join(root, 'scripts/bank-logos', src.local));
  } else {
    const dir = path.join(repo, 'assets/logos', src.slug);
    const svg = path.join(dir, 'symbol.svg');
    const png = path.join(dir, 'symbol.png');
    // Render the vector large so the downscale stays sharp.
    if (existsSync(svg)) input = sharp(svg, { density: 1200 });
    else if (existsSync(png)) input = sharp(png);
    else throw new Error(`${id}: no symbol in ${dir}`);
  }
  // Trim transparent margins, then fit the mark whole into the square cell, centred.
  const trimmed = await input.trim().png().toBuffer();
  return sharp(trimmed)
    .resize(CELL, CELL, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png()
    .toBuffer();
}

const cells = await Promise.all(ids.map(cell));
const png = await sharp({
  create: { width: CELL * ids.length, height: CELL, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } },
})
  .composite(cells.map((input, i) => ({ input, left: i * CELL, top: 0 })))
  .png({ compressionLevel: 9 })
  .toBuffer();

// The file name carries a content hash: cell positions change with the bank list, so a cached
// older sprite under the same URL would show the wrong logos.
const banksDir = path.join(root, 'public/banks');
for (const f of readdirSync(banksDir)) if (/^sprite(-[0-9a-f]+)?\.png$/.test(f)) rmSync(path.join(banksDir, f));
const file = `sprite-${createHash('sha256').update(png).digest('hex').slice(0, 8)}.png`;
writeFileSync(path.join(banksDir, file), png);

writeFileSync(
  path.join(root, 'src/features/banks/bankSprite.generated.ts'),
  `// Generated by scripts/build-bank-sprite.mjs. Do not edit by hand.
export const SPRITE_URL = '/banks/${file}';
export const SPRITE_CELL = ${CELL};
export const SPRITE_IDS = [
${ids.map((id) => `  '${id}',`).join('\n')}
] as const;
`,
);
console.log(`${file}: ${ids.length} banks, ${CELL}px cells`);
