import '../../../design-system/tokens.css';
import './ds.css';

import type { Metadata, Viewport } from 'next';
import localFont from 'next/font/local';
import React from 'react';

import { Root } from '@/components/ds';

import tokens from '../../../design-system/tokens.json';
import { Providers } from '../providers';
import { metadata as rootMetadata, viewport as rootViewport } from '../rootMetadata';

// Design system fonts: Figtree for interface text, Bricolage Grotesque for display.
// Self-hosted variable woff2 covering latin + latin-ext subsets (including ₹ and tabular numbers).
const figtree = localFont({
  src: '../fonts/Figtree-latin-ext.woff2',
  variable: '--ds-font-text',
  display: 'swap',
  weight: '500 800',
});

const bricolageGrotesque = localFont({
  src: '../fonts/BricolageGrotesque-latin-ext.woff2',
  variable: '--ds-font-display',
  display: 'swap',
  weight: '600 800',
});

// The TopBar sits on bg-surface; the browser/status bar takes that token's value per theme.
const surface = tokens.color.tokens.find((t) => t.name === 'bg-surface')!.value;

// iPhone portrait launch screens (CSS px width x height @ pixel ratio), generated by scripts/gen-splash.mjs.
const SPLASH: Array<[number, number, number]> = [
  [430, 932, 3],
  [428, 926, 3],
  [414, 896, 3],
  [414, 896, 2],
  [393, 852, 3],
  [390, 844, 3],
  [375, 812, 3],
  [375, 667, 2],
];

export const metadata: Metadata = {
  ...rootMetadata,
  appleWebApp: {
    capable: true,
    statusBarStyle: 'default',
    title: 'FinanceOS',
    startupImage: SPLASH.map(([w, h, r]) => ({
      url: `/splash/splash-${w * r}x${h * r}.png`,
      media: `(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${r}) and (orientation: portrait)`,
    })),
  },
};
/* Dinero: the on-screen keyboard overlays the page without resizing the layout viewport, so a phone
   sheet keeps its size and position and the keyboard simply covers its footer. Legacy keeps the
   shared `resizes-content` (its bottom bars rise above the keyboard). */
export const viewport: Viewport = {
  ...rootViewport,
  interactiveWidget: 'resizes-visual',
  themeColor: [
    { media: '(prefers-color-scheme: light)', color: surface.light },
    { media: '(prefers-color-scheme: dark)', color: surface.dark },
  ],
  // Draw under the notch and home bar; the shell pads itself with the safe-area utilities.
  viewportFit: 'cover',
};

/** Root layout of the Dinero UI: loads only tokens.css, ds.css and Figtree/Bricolage. */
export default function DesignSystemLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html
      lang="en"
      className={`${figtree.variable} ${bricolageGrotesque.variable}`}
      suppressHydrationWarning
    >
      <body className="antialiased" suppressHydrationWarning>
        <Providers>
          <Root>{children}</Root>
        </Providers>
      </body>
    </html>
  );
}
